void CButeMgr::LookupCodes(short State, unsigned char currentChar)
{
	m_token = TransTable[State][CharClass(currentChar)].A;
	m_tokenMinor = TransTable[State][CharClass(currentChar)].B;

	if (m_token == IdTok)
	{
		CReservedWords::CReservedWord* p = s_reservedWords.Lookup(m_szTokenString);
		if (p)
		{
			m_token = (short)p->m_token;
			m_tokenMinor = (short)p->m_tokenMinor;
		}
	}
}


bool CButeMgr::ScanTok()
{
	short State = StartState;
	std::size_t Pos;

	Pos = 0;
	for (;;)
	{
		switch (Action(State, m_currentChar))
		{
			case Error:
				DisplayMessage("Bad symbol encountered.", m_lineNumber);
				return false;
			case MoveAppend:
				State = NextState(State, m_currentChar);
				if (Pos + 1 >= sizeof(m_szTokenString)) { DisplayMessage("Attribute token is too long"); return false; }
				m_szTokenString[Pos++] = m_currentChar;
				if (m_pSaveData && m_bPutChar && m_currentChar)
					*m_pSaveData << m_currentChar;
				ConsumeChar();
				break;
			case MoveNoAppend:
				State = NextState(State, m_currentChar);
				if (m_pSaveData && m_bPutChar && m_currentChar)
					*m_pSaveData << m_currentChar;
				ConsumeChar();
				break;
			case HaltAppend:
				LookupCodes(State, m_currentChar);
				if (Pos + 1 >= sizeof(m_szTokenString)) { DisplayMessage("Attribute token is too long"); return false; }
				m_szTokenString[Pos++] = m_currentChar;
				if (m_pSaveData && m_bPutChar && m_currentChar)
					*m_pSaveData << m_currentChar;
				ConsumeChar();
				if (m_token == 0) { State = StartState; Pos = 0; continue; }
				m_szTokenString[Pos] = '\0';
				return true;
			case HaltNoAppend:
				LookupCodes(State, m_currentChar);
				if (m_pSaveData && m_bPutChar && m_currentChar)
					*m_pSaveData << m_currentChar;
				ConsumeChar();
				if (m_token == 0) { State = StartState; Pos = 0; continue; }
				m_szTokenString[Pos] = '\0';
				return true;
			case HaltReuse:
				m_szTokenString[Pos] = '\0';
				LookupCodes(State, m_currentChar);
				if (m_token == 0) { State = StartState; Pos = 0; continue; }
				return true;
		}
	}
	return true;
}


bool CButeMgr::Match(int Tok)
{
	if (!ScanTok())
		return false;
	if (m_token != Tok)
	{
		DisplayMessage("A formatting error in the attribute file was encountered");
		return false;
	}
	return true;
}


bool CButeMgr::Statement()
{
	int left, top, right, bottom;
	int x, y;
	double i, j, k;
	double doubleValue;
	float floatValue;
	int intValue;
	DWORD dwordValue;
	BYTE byteValue;
	bool boolValue;
	char **endptr = NULL;
	bool bDuplicate = false;

	m_sAttribute = m_szTokenString;

	if (!m_pSaveData && m_pCurrTabOfItems->lookup(m_sAttribute))
	{
		DisplayMessage("duplicate symbol encountered - %s", m_sAttribute.GetBuffer(0));
		bDuplicate = true;
	}

	if (!Match(EqualTok))
		return false;

	if (m_pSaveData)
	{
		m_bPutChar = false;
		*m_pSaveData << ' ';
	}

	if (!ScanTok())
		return false;

	switch (m_token)
	{
		case PosIntegerTok:
		case NegIntegerTok:
			intValue = atoi(m_szTokenString);
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(IntType, intValue));
			}
			else
			{
				intValue = GetInt(m_sTagName, m_sAttribute);
				*m_pSaveData << intValue;
			}
			break;
		case CastDwordTok:
			if (!Match(PosIntegerTok))
				return false;
			dwordValue = strtoul(m_szTokenString, endptr, 10);
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(DwordType, dwordValue));
			}
			else
			{
				dwordValue = GetDword(m_sTagName, m_sAttribute);
				*m_pSaveData << "(DWORD)" << dwordValue;
			}
			break;
		case CastByteTok:
			if (!Match(PosIntegerTok))
				return false;
			byteValue = atoi(m_szTokenString);
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(ByteType, byteValue));
			}
			else
			{
				byteValue = GetByte(m_sTagName, m_sAttribute);
				*m_pSaveData << "(BYTE)" << (DWORD)byteValue;
			}
			break;
		case BoolTok:
			boolValue = m_tokenMinor == 1;
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(BoolType, boolValue));
			}
			else
			{
				boolValue = GetBool(m_sTagName, m_sAttribute);
				if (boolValue)
					*m_pSaveData << "TRUE";
				else
					*m_pSaveData << "FALSE";
			}
			break;
		case CastFloatTok:
			if (!Match(DoubleTok))
				return false;
			floatValue = (float)atof(m_szTokenString);
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(FloatType, floatValue));
			}
			else
			{
				floatValue = GetFloat(m_sTagName, m_sAttribute);
				*m_pSaveData << "(FLOAT)" << floatValue;
			}
			break;
		case FloatTok:
			floatValue = (float)atof(m_szTokenString);
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(FloatType, floatValue));
			}
			else
			{
				floatValue = GetFloat(m_sTagName, m_sAttribute);
				*m_pSaveData << floatValue << "f";
			}
			break;
		case DoubleTok:
			doubleValue = atof(m_szTokenString);
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(DoubleType, doubleValue));
			}
			else
			{
				doubleValue = GetDouble(m_sTagName, m_sAttribute);
				*m_pSaveData << doubleValue;
			}
			break;
		case RectTok:
			if (sscanf(m_szTokenString, "(%d, %d, %d, %d)", &left, &top, &right, &bottom) != 4) { DisplayMessage("Invalid compound attribute value"); return false; }
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(RectType, CRect(left, top, right, bottom)));
			}
			else
			{
				CRect rc = GetRect(m_sTagName, m_sAttribute);
				*m_pSaveData << "(" << rc.left << ", " << rc.top << ", " << rc.right << ", " << rc.bottom << ")";
			}
			break;
		case PointTok:
			if (sscanf(m_szTokenString, "(%d, %d)", &x, &y) != 2) { DisplayMessage("Invalid compound attribute value"); return false; }
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(PointType, CPoint(x, y)));
			}
			else
			{
				CPoint pt = GetPoint(m_sTagName, m_sAttribute);
				*m_pSaveData << "(" << pt.x << ", " << pt.y << ")";
			}
			break;
		case VectorTok:
			if (sscanf(m_szTokenString, "<%lf, %lf, %lf>", &i, &j, &k) != 3) { DisplayMessage("Invalid compound attribute value"); return false; }
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(VectorType, CAVector(i, j, k)));
			}
			else
			{
				CAVector v = GetVector(m_sTagName, m_sAttribute);
				*m_pSaveData << "<" << v.Geti() << ", " << v.Getj() << ", " << v.Getk() << ">";
			}
			break;
		case RangeTok:
			if (sscanf(m_szTokenString, "[%lf, %lf]", &i, &j) != 2) { DisplayMessage("Invalid compound attribute value"); return false; }
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(RangeType, CARange(i, j)));
			}
			else
			{
				CARange range = GetRange(m_sTagName, m_sAttribute);
				*m_pSaveData << "[" << range.GetMin() << ", " << range.GetMax() << "]";
			}
			break;
		case StringTok:
			if (!m_pSaveData)
			{
				if (!bDuplicate)
					m_pCurrTabOfItems->add(m_sAttribute, new CSymTabItem(StringType, CString(m_szTokenString)));
			}
			else
			{
				CString s = GetString(m_sTagName, m_sAttribute);
				s.Replace("\"", "\"\"");
				*m_pSaveData << '"' << s.GetBuffer(0) << '"';
			}
			break;
		default:
			DisplayMessage("Invalid token encountered.");
			return false;
			break;
	}

	if (m_pSaveData)
		m_bPutChar = true;
	return true;
}


bool CButeMgr::StatementList()
{
	for (;;)
	{
		if (!Statement())
			return false;
		if (!ScanTok())
			return  false;

		if (m_token == TagBegTok || m_token == EofTok)
			return true;
		else if (m_token != IdTok)
			return false;
	}
	return true;
}


bool CButeMgr::Tag()
{
	if (!Match(IdTok))
		return false;
	m_sTagName = m_szTokenString;
	if (!m_pSaveData)
	{
		if (m_tagTab.lookup(m_szTokenString))
		{
			DisplayMessage("Duplicate tag encountered - %s", m_szTokenString);
			return false;
		}

		// Assigned first, then passed: shipped stores the new table into
		// m_pCurrTabOfItems before the add() call and ignores add()'s result.
		m_pCurrTabOfItems = new TableOfItems;
		m_tagTab.add(m_szTokenString, m_pCurrTabOfItems);
	}
	if (!Match(TagEndTok))
		return false;

	return true;
}


void CButeMgr::AuxTabItemsSave(const char* sz, CSymTabItem* pItem, void* p)
{
	std::ostream* pSaveData = static_cast<std::ostream*>(p);

	*pSaveData << "\r\n" << sz << " = ";

	switch (pItem->SymType)
	{
	case IntType:
		*pSaveData << *pItem->data.i;
		break;
	case DwordType:
		*pSaveData << "(DWORD)" << *pItem->data.dw;
		break;
	case ByteType:
		*pSaveData << "(BYTE)" << (DWORD)*pItem->data.byte;
		break;
	case BoolType:
		if (*pItem->data.b)
			*pSaveData << "TRUE";
		else
			*pSaveData << "FALSE";
		break;
	case FloatType:
		*pSaveData << *pItem->data.f << 'f';
		break;
	case DoubleType:
		*pSaveData << *pItem->data.d;
		break;
	case StringType:
		{
			CString s = *pItem->data.s;
			s.Replace("\"", "\"\"");
			*pSaveData << '"' << (LPCSTR)s << '"';
			break;
		}
	case RectType:
		*pSaveData << '(' << pItem->data.r->left << ", " << pItem->data.r->top << ", " << pItem->data.r->right << ", " << pItem->data.r->bottom << ')';
		break;
	case PointType:
		*pSaveData << "(" << pItem->data.point->x << ", " << pItem->data.point->y << ")";
		break;
	case VectorType:
		*pSaveData << "<" << pItem->data.v->Geti() << ", " << pItem->data.v->Getj() << ", " << pItem->data.v->Getk() << ">";
		break;
	case RangeType:
		*pSaveData << "[" << pItem->data.range->GetMin() << ", " << pItem->data.range->GetMax() << "]";
		break;
	}
}


void CButeMgr::NewTabsSave(const char* sz, TableOfItems* pTabOfItems, void* p)
{
	std::ostream* pSaveData = static_cast<std::ostream*>(p);

	*pSaveData << "\r\n\r\n" << "[" << sz << "]";

	pTabOfItems->traverse(AuxTabItemsSave, p);
}


bool CButeMgr::TagList()
{
	ConsumeChar();
	if (!ScanTok())
		return false;
	if (m_token == EofTok)
		return true;
	else if (m_token != TagBegTok)
		return false;
	while (m_token != EofTok)
	{
		if (!Tag())
			return false;

		if (m_pSaveData)
		{
			TableOfItems* pTableOfItems = m_auxTagTab.lookup(m_sTagName);
			if (pTableOfItems)
			{
				pTableOfItems->traverse(AuxTabItemsSave, m_pSaveData);
			}
		}
		if (!ScanTok())
			return false;

		if (m_token == EofTok)
			return true;

		if (m_token == TagBegTok)
			continue;

		if (m_token != IdTok)
			return false;

		if (!StatementList())
			return false;
	}
	return true;
}


bool CButeMgr::Save(const char* filename)
{
    const char* destination = filename ? filename : static_cast<const char*>(m_sAttributeFilename);
    if (!*destination) return false;
    Reset();
    std::istringstream input(m_sourceText);
    std::ostringstream output;
    input.imbue(std::locale::classic());
    output.imbue(std::locale::classic());
    output.setf(std::ios::showpoint | std::ios::fixed);
    m_pData = &input;
    m_pSaveData = &output;
    m_bPutChar = true;
    struct ResetStreams {
        CButeMgr& owner;
        ~ResetStreams() { owner.m_pData = nullptr; owner.m_pSaveData = nullptr; owner.m_bPutChar = false; }
    } reset{*this};
    try {
        if (!TagList()) return false;
        m_newTagTab.traverse(NewTabsSave, m_pSaveData);
        auto text = output.str();
        if (m_bCrypt) {
            std::istringstream clear(text);
            std::ostringstream encoded;
            m_cryptMgr.Encrypt(clear, encoded);
            text = encoded.str();
        }
        nolf::platform::atomic_write(destination, std::as_bytes(std::span(text.data(), text.size())));
        return true;
    } catch (const std::exception& error) {
        DisplayMessage("%s", error.what());
        return false;
    }
}


