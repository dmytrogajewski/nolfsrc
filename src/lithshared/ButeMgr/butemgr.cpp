void CButeMgr::ConsumeChar()
{
	int c = m_pData->get() - m_decryptCode;

	if (m_pData->eof())
	{
		m_currentChar = 0;
		return;
	}

	if (m_bLineCounterFlag)
		m_lineNumber++;

	m_currentChar = (unsigned char)c;
	m_bLineCounterFlag = (c == '\n');
	m_checksum += c;
}


